/** Every IPC message. Discriminated union on `type`. */
export type IpcMessage =
  | IpcHello
  | IpcAuthState
  | IpcWorkspace
  | IpcOpenFiles
  | IpcSelection
  | IpcTaskState
  | IpcChatPrompt
  | IpcChatPromptResult
  | IpcWorkspaceReadRequest
  | IpcWorkspaceReadResult
  | IpcProposedEdit
  | IpcEditReviewResult
  | IpcCommandRequest
  | IpcCommandReviewResult
  | IpcCommandOutput
  | IpcCancel
  | IpcGatewayHealth
  | IpcMemoryHealth
  | IpcVersionState
  | IpcCompanionState
  | IpcCompanionAction
  | IpcHeartbeat;

/**
 * Messages that expect a response. The adapter (or extension) MUST reply with
 * a message carrying the same `nonce`. The set is the intersection of
 * "request-like" shapes — proposedEdit (expects editReviewResult),
 * commandRequest (expects commandReviewResult), hello (expects authState or
 * pipe close). Everything else is fire-and-forget.
 */
export type IpcRequest =
  | IpcHello
  | IpcChatPrompt
  | IpcWorkspaceReadRequest
  | IpcProposedEdit
  | IpcCommandRequest;

/**
 * Messages that respond to a request. `editReviewResult` answers
 * `proposedEdit`; `commandReviewResult` answers `commandRequest`. `hello` is
 * answered implicitly by `authState` (the adapter emits authState once it
 * has verified the secret).
 */
export type IpcResponse =
  | IpcAuthState
  | IpcChatPromptResult
  | IpcWorkspaceReadResult
  | IpcEditReviewResult
  | IpcCommandReviewResult;

/**
 * Fire-and-forget events. Neither side awaits a response. This is the
 * complement of (IpcRequest ∪ IpcResponse) within IpcMessage.
 */
export type IpcEvent =
  | IpcWorkspace
  | IpcOpenFiles
  | IpcSelection
  | IpcTaskState
  | IpcCommandOutput
  | IpcCancel
  | IpcGatewayHealth
  | IpcMemoryHealth
  | IpcVersionState
  | IpcCompanionState
  | IpcCompanionAction
  | IpcHeartbeat;

// ---------------------------------------------------------------------------
// Replay protection
// ---------------------------------------------------------------------------

/**
 * Reference replay-protection tracker. Both sides MUST run one. Nonces are
 * unique-per-request random hex strings; the tracker rejects a nonce it has
 * seen within `maxAgeMs` and ages out older entries on each `check()` so the
 * table doesn't grow unbounded.
 *
 * The default 5-minute window matches the heartbeat interval × 20 — long
 * enough to catch a replayed request that crossed a heartbeat boundary, short
 * enough that a legitimately-retried request (after a pipe reconnect) isn't
 * falsely rejected.
 *
 * Note: this is NOT a substitute for transport encryption. The named pipe is
 * local-only (same machine), so replay is the realistic threat — a malicious
 * process on the box sniffing the pipe and replaying a commandRequest. The
 * tracker defeats that. For remote attackers the pipe isn't reachable.
 */
export class NonceTracker {
  private readonly seen = new Map<string, number>();
  private readonly maxAgeMs: number;

  constructor(maxAgeMs = 5 * 60 * 1000) {
    this.maxAgeMs = maxAgeMs;
  }

  /**
   * Returns true if the nonce is fresh (first time seen), false if it's a
   * replay (seen within the max-age window). Aging is performed lazily on
   * each call so we don't need a timer thread — important for the extension
   * side where we can't assume a long-lived event loop.
   */
  check(nonce: string, now = Date.now()): boolean {
    this.ageOut(now);
    if (this.seen.has(nonce)) {
      return false;
    }
    this.seen.set(nonce, now);
    return true;
  }

  /** Remove entries older than the max-age window. Called internally. */
  private ageOut(now: number): void {
    const cutoff = now - this.maxAgeMs;
    for (const [nonce, ts] of this.seen) {
      if (ts < cutoff) {
        this.seen.delete(nonce);
      }
    }
  }

  /** Number of nonces currently tracked. Exposed for tests + diagnostics. */
  get size(): number {
    return this.seen.size;
  }

  /** Clear all tracked nonces. Exposed for tests. */
  reset(): void {
    this.seen.clear();
  }
}

/**
 * Generate a fresh nonce. 16 random bytes → 32 hex chars. Collisions are
 * astronomically unlikely (2^128 space); the NonceTracker handles the rare
 * collision by rejecting the second occurrence.
 */
export function generateNonce(): string {
  return randomBytes(16).toString('hex');
}

/**
 * Type guard: is the given value a valid IpcMessage? Cheap structural check
 * on `type` + `nonce`. Used by the adapter before dispatching a handler —
 * malformed input is logged and dropped, not thrown on.
 */
export function isIpcMessage(value: unknown): value is IpcMessage {
  if (typeof value !== 'object' || value === null) return false;
  const v = value as Record<string, unknown>;
  if (typeof v.type !== 'string' || typeof v.nonce !== 'string' || typeof v.ts !== 'string') {
    return false;
  }
  const validTypes: ReadonlySet<string> = new Set<IpcMessage['type']>([
    'hello',
    'authState',
    'workspace',
    'openFiles',
    'selection',
    'taskState',
    'chatPrompt',
    'chatPromptResult',
    'workspaceReadRequest',
    'workspaceReadResult',
    'proposedEdit',
    'editReviewResult',
    'commandRequest',
    'commandReviewResult',
    'commandOutput',
    'cancel',
    'gatewayHealth',
    'memoryHealth',
    'versionState',
    'companionState',
    'companionAction',
    'heartbeat',
  ]);
  return validTypes.has(v.type);
}
